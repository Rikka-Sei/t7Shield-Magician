//! §4.10 的命令 UID 表常量（唯一权威来源；其它模块不得再写一份 UID 字节）。

/// TCG 对象的 UID：8 字节。
pub type Uid = [u8; 8];

/// 会话管理器 SMUID（StartSession 的 InvokingID）。
pub const SMUID: Uid = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF];

/// LOCKINGSP（StartSession 的 SPID 目标）。
pub const LOCKINGSP: Uid = [0x00, 0x00, 0x02, 0x05, 0x00, 0x00, 0x00, 0x02];

/// ADMIN1（HostSigningAuthority）。
pub const ADMIN1: Uid = [0x00, 0x00, 0x00, 0x09, 0x00, 0x01, 0x00, 0x01];

/// MBRControl 表。
pub const MBRCONTROL: Uid = [0x00, 0x00, 0x08, 0x03, 0x00, 0x00, 0x00, 0x01];

/// LockingRangeGlobal 表。
pub const LOCKINGRANGE_GLOBAL: Uid = [0x00, 0x00, 0x08, 0x02, 0x00, 0x00, 0x00, 0x01];

/// DataStore 表。
pub const DATASTORE: Uid = [0x00, 0x00, 0x10, 0x01, 0x00, 0x00, 0x00, 0x00];

/// StartSession 方法（MethodID）。
pub const STARTSESSION_METHOD: Uid = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0x02];

/// Set 方法（MethodID）。
pub const SET_METHOD: Uid = [0x00, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x17];

#[cfg(test)]
mod tests {
    use super::*;

    /// §4.10 UID 表共 8 项，逐项与规格表格一致。
    #[test]
    fn test_uid_table_matches_spec() {
        assert_eq!(SMUID, [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF]);
        assert_eq!(LOCKINGSP, [0x00, 0x00, 0x02, 0x05, 0x00, 0x00, 0x00, 0x02]);
        assert_eq!(ADMIN1, [0x00, 0x00, 0x00, 0x09, 0x00, 0x01, 0x00, 0x01]);
        assert_eq!(MBRCONTROL, [0x00, 0x00, 0x08, 0x03, 0x00, 0x00, 0x00, 0x01]);
        assert_eq!(
            LOCKINGRANGE_GLOBAL,
            [0x00, 0x00, 0x08, 0x02, 0x00, 0x00, 0x00, 0x01]
        );
        assert_eq!(DATASTORE, [0x00, 0x00, 0x10, 0x01, 0x00, 0x00, 0x00, 0x00]);
        assert_eq!(
            STARTSESSION_METHOD,
            [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0x02]
        );
        assert_eq!(SET_METHOD, [0x00, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x17]);
    }
}
